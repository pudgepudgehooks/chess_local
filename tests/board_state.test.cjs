const assert = require('node:assert/strict');
const {BoardSession, placement, pieceTransitions} = require('../board_component/board_state.js');
assert.deepEqual(pieceTransitions({e2:'P'}, {e4:'P'}), [{from:'e2',to:'e4'}]);
assert.deepEqual(pieceTransitions({e4:'P',d5:'p'}, {d5:'P'}), [{from:'e4',to:'d5'}]);
assert.deepEqual(pieceTransitions({d5:'P'}, {e4:'P',d5:'p'}), [{from:'d5',to:'e4'},{to:'d5'}]);
assert.deepEqual(pieceTransitions({e1:'K',h1:'R'}, {g1:'K',f1:'R'}), [{from:'e1',to:'g1'},{from:'h1',to:'f1'}]);
assert.deepEqual(pieceTransitions({g1:'K',f1:'R'}, {e1:'K',h1:'R'}), [{from:'g1',to:'e1'},{from:'f1',to:'h1'}]);
assert.deepEqual(pieceTransitions({e7:'P',f8:'r'}, {f8:'N'}), [{from:'e7',to:'f8'}]);
assert.deepEqual(pieceTransitions({f8:'N'}, {e7:'P',f8:'r'}), [{from:'f8',to:'e7'},{to:'f8'}]);
assert.deepEqual(pieceTransitions({a2:'p'}, {a1:'q'}), [{from:'a2',to:'a1'}]);
assert.deepEqual(pieceTransitions({e5:'P',d5:'p'}, {d6:'P'}), [{from:'e5',to:'d6'}]);
assert.deepEqual(pieceTransitions({e4:'P'}, {e4:'P'}), []);
const start = '8/8/8/8/8/8/4P3/4K2k w - - 0 1';
const moved = '8/8/8/8/4P3/8/8/4K2k b - - 0 1';
const next = '8/8/8/8/4P3/8/7k/4K3 w - - 1 2';
let session = new BoardSession(start);
assert(session.start('e2e4', 'first', {e2e4:moved}));
assert.equal(session.fen, moved, 'drop stays on destination while checking');
assert.equal(placement(session.fen).e4, 'P');
assert.equal(placement(session.fen).e2, undefined);
assert(!session.start('e2e4', 'duplicate', {e2e4:moved}), 'block input while pending');
assert(!session.receive({event_id:'old',status:'incorrect'}), 'ignore stale acknowledgements');
assert.equal(session.fen, moved);
assert(session.receive({event_id:'first',status:'incorrect',frames:[]}));
assert.equal(session.fen,start,'wrong answer resets the original position');
assert(!session.busy && !session.solved);
assert.equal(session.status, 'The answer is incorrect, please try again');
assert(session.beginAttempt());
assert.equal(session.status, '', 'picking up a piece clears previous feedback');
assert.equal(session.fen, start, 'beginning a retry leaves the starting position intact');
assert(!session.receive({event_id:'first',status:'incorrect',frames:[]}), 'old response cannot restore a dismissed error');
assert(session.start('e2e4', 'second', {e2e4:moved}));
const frames=[{fen:moved,uci:'e2e4',san:'e4'},{fen:next,uci:'h1h2',san:'Kh2'}];
assert(session.receive({event_id:'second',status:'correct',frames}));
assert.equal(session.fen,moved,'accepted first move stays visible');
assert(!session.busy, 'a correct answer waits for manual navigation');
assert.equal(session.index, 0, 'continuation does not advance on its own');
assert(session.retreat());
assert.equal(session.fen, start, 'Back can show the original position');
assert(!session.retreat(), 'Back stops at the original position');
assert(session.advance());
assert.equal(session.fen, moved);
assert(session.advance());
assert.equal(session.fen,next,'continuation advances the board');
assert(!session.busy && session.solved);
assert.equal(session.status, 'Click Next Puzzle to proceed.');
assert(!session.receive({event_id:'second',status:'correct',frames}),'ordinary rerun cannot replay');
assert.equal(session.fen,next);
assert(!session.start('e2e4','third',{e2e4:moved}),'solved board does not submit more attempts');
assert(!session.advance(), 'Forward stops at the last saved move');
assert(session.retreat());
assert.equal(session.fen,moved);
assert.equal(session.status, 'Correct! Use Forward and Back to review the continuation.');
assert(!session.receive({event_id:'second',status:'correct',frames}), 'reruns preserve a manual navigation step');
assert(session.advance());
assert.equal(session.fen,next);
const single = new BoardSession(start);
single.receive({event_id:'single',status:'correct',frames:[frames[0]],message:'Correct! No continuation is available for this position.'});
assert(!single.advance());
assert(single.retreat());
assert(single.advance());
assert.equal(single.status, 'Correct! No continuation is available for this position.');
session = new BoardSession(start);
assert(session.start('e2e4','failed',{e2e4:moved}));
session.receive({event_id:'failed',status:'error',frames:[]});
assert.equal(session.fen,start,'save failure also permits a retry');
console.log('Board state tests passed');
